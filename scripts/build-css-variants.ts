/**
 * Generate the CSS-only variant of every component.
 *
 * The point is that there is only ever one implementation. Each component's
 * styles are compiled by Tailwind from the same source file the Tailwind
 * variant ships, so the CSS cannot drift from the TSX — there is nothing to
 * keep in sync, because the CSS is derived from it.
 *
 * Output: public/css/{slug}.css
 *   - the utilities that component actually uses, expanded
 *   - the keyframes those utilities need
 *   - the shared buildora-* keyframes from the token file
 *
 * A consumer who does not use Tailwind installs the component, links this
 * file and the token file, and it looks the same. A consumer who does use
 * Tailwind ignores this file entirely; their build already has the same
 * utilities.
 *
 * Run: pnpm registry:css
 */
import * as fs from "node:fs";
import * as path from "node:path";
import { createRequire } from "node:module";

const root = process.cwd();
const require_ = createRequire(path.join(root, "apps", "web", "package.json"));

const postcss = require_("postcss");
const tailwindcss = require_("tailwindcss");
const tailwindConfig = require_("./tailwind.config.js") as Record<string, unknown>;

type Item = { slug: string; files: string[]; name: string };

/** Read the catalogue the same way the build does. */
async function loadCatalog(): Promise<Item[]> {
  const { catalog } = (await import("./catalog")) as {
    catalog: Array<{ slug: string; files: string[]; name: string }>;
  };
  return catalog;
}

/**
 * The keyframes a component may reference, from the token file.
 *
 * Parsed rather than pattern-matched: the shared file has keyframes with
 * three, four and five steps, and a regex gets them wrong.
 */
function sharedKeyframes(): Map<string, string> {
  const tokens = fs.readFileSync(
    path.join(root, "registry", "shared", "tokens.css"),
    "utf8"
  );
  const ast = postcss.parse(tokens);
  const out = new Map<string, string>();
  ast.walkAtRules("keyframes", (rule) => {
    if (rule.params.startsWith("buildora-")) out.set(rule.params, rule.toString());
  });
  return out;
}

/** The utilities one file needs, expanded by Tailwind. */
async function utilitiesFor(file: string): Promise<string> {
  const config = {
    ...tailwindConfig,
    content: [path.join(root, file)],
    darkMode: tailwindConfig.darkMode,
  } as Record<string, unknown>;

  const result = await postcss([
    tailwindcss(config as never),
    require_("autoprefixer"),
  ]).process("@tailwind utilities;\n", {
    from: path.join(root, "apps", "web", "tailwind-probe.css"),
  });

  return result.css;
}

/**
 * Flatten Tailwind's `@layer utilities { ... }` into plain CSS and lift every
 * @keyframes out of it, so the file is a flat list of rules and keyframes.
 */
function flatten(css: string): { rules: string; keyframes: Map<string, string> } {
  const ast = postcss.parse(css);
  const rules: string[] = [];
  const keyframes = new Map<string, string>();

  const visit = (container: { nodes: Array<Record<string, unknown>> }) => {
    for (const node of container.nodes as Array<{
      type: string;
      name?: string;
      params?: string;
      nodes?: unknown[];
      toString: () => string;
      [k: string]: unknown;
    }>) {
      if (node.type === "atrule" && node.name === "keyframes" && node.params) {
        keyframes.set(node.params, node.toString());
        continue;
      }
      if (node.type === "atrule" && node.name === "layer") {
        const inner = node.nodes as Array<{ type: string; params?: string; toString: () => string; nodes?: unknown[] }>;
        for (const child of inner) {
          if (child.type === "atrule" && child.name === "keyframes" && child.params) {
            keyframes.set(child.params, child.toString());
            continue;
          }
          rules.push(child.toString());
        }
        continue;
      }
      rules.push(node.toString());
    }
  };

  visit(ast as unknown as { nodes: Array<Record<string, unknown>> });

  return { rules: rules.join("\n").trim(), keyframes };
}

/** The names of the animations a stylesheet actually uses. */
function usedAnimationNames(css: string): Set<string> {
  const used = new Set<string>();
  for (const m of css.matchAll(/animation(?:-name)?\s*:\s*([^;}\n]+)/g)) {
    for (const name of m[1].matchAll(/([\w-]+)/g)) used.add(name[1]);
  }
  return used;
}

function headerFor(name: string, slug: string): string {
  return `/* ${name} — CSS variant of @buildora/${slug}
 *
 * Generated by \`pnpm registry:css\` from the same source the Tailwind
 * variant ships, so it cannot drift. Link it after the Buildora tokens
 * file:
 *
 *   import "@/styles/buildora/tokens.css";
 *   import "@/styles/buildora/${slug}.css";
 *
 * If you already use Tailwind, ignore this file — your build already
 * has these utilities.
 */`;
}

async function main() {
  const catalog = await loadCatalog();
  // Next serves the app's own public directory, not the repo root.
  const outDir = path.join(root, "apps", "web", "public", "css");
  fs.mkdirSync(outDir, { recursive: true });

  const shared = sharedKeyframes();
  let written = 0;
  let skipped = 0;

  for (const item of catalog) {
    const tsx = item.files.find((f) => f.endsWith(".tsx"));
    if (!tsx) {
      skipped++;
      continue;
    }
    const abs = path.join(root, tsx);
    if (!fs.existsSync(abs)) {
      skipped++;
      continue;
    }

    const raw = await utilitiesFor(tsx);
    const { rules, keyframes } = flatten(raw);
    const used = usedAnimationNames(rules);

    // The shared keyframes this component's styles reference.
    for (const [name, block] of shared) {
      if (used.has(name) && !keyframes.has(name)) keyframes.set(name, block);
    }

    const parts = [
      headerFor(item.name, item.slug),
      rules,
      ...[...keyframes.values()],
    ].filter(Boolean);

    fs.writeFileSync(
      path.join(outDir, `${item.slug}.css`),
      `${parts.join("\n\n").trim()}\n`,
      "utf8"
    );
    written++;
  }

  console.log(
    `CSS variants: ${written} written, ${skipped} skipped (no TSX) → apps/web/public/css`
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
