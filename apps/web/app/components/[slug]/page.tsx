import { notFound } from "next/navigation";
import * as fs from "node:fs";
import * as path from "node:path";
// Cache invalidation: force Next.js to reload this file
import { allComponents, getComponent } from "@/lib/registry";
import { ComponentDetail } from "./detail";

export function generateStaticParams() {
  return allComponents.map((c) => ({ slug: c.slug }));
}

export async function generateMetadata({ params }: { params: { slug: string } }) {
  const c = allComponents.find((x) => x.slug === params.slug);
  const title = c ? `${c.name} — Buildora` : "Component — Buildora";
  const description = c?.description ?? "Buildora component";
  return {
    title,
    description,
    openGraph: { title, description, type: "website", images: ["/og.jpg"] },
    twitter: { card: "summary_large_image", title, description, images: ["/og.jpg"] },
  };
}

/**
 * The CSS-only variant, generated by `pnpm registry:css` from the same
 * source the Tailwind variant ships.
 */
function cssVariant(slug: string): string | null {
  const file = path.join(process.cwd(), "public", "css", `${slug}.css`);
  try {
    return fs.readFileSync(file, "utf8");
  } catch {
    return null;
  }
}

export default async function Page({ params }: { params: { slug: string } }) {
  const item = await getComponent(params.slug);
  if (!item) notFound();
  return (
    <ComponentDetail
      slug={params.slug}
      item={item}
      css={cssVariant(params.slug)}
    />
  );
}
